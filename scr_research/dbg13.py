import sys, re, html, os
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
for fn in ("wiki_terrain.html", "scmjs_dd2_doc.html"):
    p = os.path.join(r"F:\KF\XJZB\scr_research", fn)
    t = open(p, encoding="utf-8", errors="replace").read()
    t = re.sub(r"<script.*?</script>", " ", t, flags=re.S|re.I)
    t = re.sub(r"<style.*?</style>", " ", t, flags=re.S|re.I)
    t = re.sub(r"<(br|/p|/li|/tr|/h\d)[^>]*>", "\n", t, flags=re.I)
    t = re.sub(r"<[^>]+>", " ", t)
    t = html.unescape(t)
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r"\n\s*\n+", "\n", t)
    out = os.path.join(r"F:\KF\XJZB\scr_research", fn.replace(".html", ".txt"))
    open(out, "w", encoding="utf-8").write(t)
    print(fn, "->", out, len(t), "chars")
